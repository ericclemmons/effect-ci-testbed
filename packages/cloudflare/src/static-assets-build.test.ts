import assert from "node:assert/strict"
import { createHash } from "node:crypto"
import test from "node:test"
import { prepareBuiltStaticAssets, prepareStaticBuildSource } from "./static-assets-build.ts"
const hash = (value: string | Uint8Array) => createHash("sha256").update(value).digest("hex")
const revision = "a".repeat(40), source = 'const message: string = "Built";', code = 'const message = "Built";'
const manifest = (files = [{ path: "site/app.ts", text: source }, { path: "site/index.html", text: "<script src='/app.js'></script>" }, { path: "site/style.css", text: "body{}" }]) =>
  new TextEncoder().encode(JSON.stringify({ version: 1, files: files.map(f => ({ path: f.path, base64: Buffer.from(f.text).toString("base64"), executable: false })) }))
const receipt = () => ({ runtime: "dynamic-worker", containers: 0, tool: "sucrase-3.35.1-typescript", code,
  sourceDigest: hash(source), outputDigest: hash(code), toolDigest: "b".repeat(64) })

test("complete fixed output manifest binds raw source, compiler and emitted bytes without claiming generated bytes are Git blobs", async () => {
  const bytes = manifest(), digest = hash(bytes), pending = prepareStaticBuildSource(revision, bytes, digest)
  bytes.fill(0)
  assert.equal((await pending).source, source, "source bytes captured before digest await")
  const raw = manifest(), result = await prepareBuiltStaticAssets(revision, raw, hash(raw), receipt())
  assert.deepEqual(result.assets.map(a => a.path), ["app.js", "index.html", "style.css"])
  assert.equal(Buffer.from(result.assets[0]!.base64, "base64").toString(), code)
  assert.equal(result.build.sourceManifestDigest, hash(raw)); assert.equal(result.build.outputManifestDigest, hash(result.bytes))
  assert.equal(result.build.sourceDigest, hash(source)); assert.equal(result.build.outputDigest, hash(code))
  assert.notEqual(result.manifestDigest, result.build.sourceManifestDigest)
})
test("foreign paths, executable/extra files, corrupt identities and untrusted compiler receipt shapes cannot authorize publication", async () => {
  const raw = manifest(), digest = hash(raw)
  for (const files of [[{ path: "site/app.js", text: code }], [{ path: "../app.ts", text: source }]]) {
    const bytes = manifest(files); await assert.rejects(prepareStaticBuildSource(revision, bytes, hash(bytes)))
  }
  for (const changed of [{ ...receipt(), sourceDigest: "c".repeat(64) }, { ...receipt(), outputDigest: "c".repeat(64) },
    { ...receipt(), tool: "actor-selected" }, { ...receipt(), token: "private" }, { ...receipt(), containers: 1 },
    { ...receipt(), code: "x".repeat(32769) }, { ...receipt(), code: "\0" }, { ...receipt(), toolDigest: "bad" }])
    await assert.rejects(prepareBuiltStaticAssets(revision, raw, digest, changed))
  let called = false; const getter = receipt()
  Object.defineProperty(getter, "code", { get() { called = true; throw Error("private") } })
  await assert.rejects(prepareBuiltStaticAssets(revision, raw, digest, getter)); assert.equal(called, false)
  const executable = JSON.parse(new TextDecoder().decode(raw)); executable.files[0].executable = true
  const bad = new TextEncoder().encode(JSON.stringify(executable))
  await assert.rejects(prepareStaticBuildSource(revision, bad, hash(bad)))
  await assert.rejects(prepareStaticBuildSource(revision, raw, "c".repeat(64)))
})
